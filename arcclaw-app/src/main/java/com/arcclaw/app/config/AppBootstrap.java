    private static void validateAndAutoFixEmbeddingConfig(Path binaryDir) {
        Path envFile = binaryDir.resolve(".env");
        String provider = System.getProperty("ARCCLAW_EMBED_PROVIDER", System.getenv("ARCCLAW_EMBED_PROVIDER"));
        String baseUrl = System.getProperty("ARCCLAW_EMBED_BASE_URL", System.getenv("ARCCLAW_EMBED_BASE_URL"));

        // Force Jina if provider/URL mismatch detected (e.g. Ollama provider with Jina URL)
        if (baseUrl != null && baseUrl.contains("jina.ai") && !"jina".equalsIgnoreCase(provider)) {
            System.err.println("[ArcClaw] ℹ️  Embedding provider mismatch (Jina URL with " + provider + " provider) — auto-fixing to 'jina'.");
            forcePatchEnvFile(envFile, "ARCCLAW_EMBED_PROVIDER", "jina");
            System.setProperty("ARCCLAW_EMBED_PROVIDER", "jina");
        }

        // Force Ollama defaults if provider is ollama but URL is wrong
        if ("ollama".equalsIgnoreCase(provider) && (baseUrl == null || baseUrl.contains("jina.ai"))) {
            String defaultOllamaUrl = "http://localhost:11434";
            System.err.println("[ArcClaw] ℹ️  Ollama embedding URL missing or invalid — auto-setting to: " + defaultOllamaUrl);
            patchEnvFile(envFile, "ARCCLAW_EMBED_BASE_URL", defaultOllamaUrl);
            System.setProperty("ARCCLAW_EMBED_BASE_URL", defaultOllamaUrl);
        }
    }

    private static void fixIfMatches(Path envFile, String key, String wrongValue, String targetValue) {
        String current = System.getProperty(key, System.getenv(key));
        if (current == null || current.isBlank() || current.equals(wrongValue)) {
            if (!targetValue.equals(current)) {
                System.err.println("[ArcClaw] ℹ️  " + key + " is inconsistent with provider — auto-setting to: " + targetValue);
                patchEnvFile(envFile, key, targetValue);
                System.setProperty(key, targetValue);
            }
        }
    }

    private static void validateSandboxTools(Path binaryDir) {
        String strategyStr = System.getProperty("ARCCLAW_SANDBOX_STRATEGY", System.getenv("ARCCLAW_SANDBOX_STRATEGY"));
        SandboxStrategy strategy = SandboxStrategy.fromString(strategyStr);

        if (SandboxStrategy.PODMAN == strategy) {
            boolean podmanReachable = canRun("podman", "info");
            boolean fallbackEnabled = "true".equalsIgnoreCase(System.getProperty("arcclaw.sandbox.allow-insecure-fallback", 
                                       System.getenv("ARCCLAW_SANDBOX_ALLOW_INSECURE_FALLBACK")));

            if (!podmanReachable && !fallbackEnabled) {
                System.err.println();
                System.err.println("  ┌─ Podman Sandbox Environment");
                System.err.println("  │  ⚠️  Podman is not reachable or not running.");
                System.err.println("  │  ArcClaw uses Podman for secure code execution (Sandboxing).");
                System.err.println("  │");
                System.err.println("  │  Options:");
                System.err.println("  │  1. Enable insecure host fallback (unsafe, local-dev only)");
                System.err.println("  │  2. Skip sandbox for now (code tools will be OFFLINE)");
                System.err.println("  │");
                
                String response = readLineWithFallback(System.console(), "  └─ Select option [1-2, Default: 2]: ");
                if ("1".equals(response != null ? response.trim() : "")) {
                    System.err.println("     ✓ Insecure fallback enabled.");
                    patchEnvFile(binaryDir.resolve(".env"), "ARCCLAW_SANDBOX_ALLOW_INSECURE_FALLBACK", "true");
                    System.setProperty("arcclaw.sandbox.allow-insecure-fallback", "true");
                    System.setProperty("ARCCLAW_SANDBOX_ALLOW_INSECURE_FALLBACK", "true");
                } else {
                    System.err.println("     [skipped - code execution will fail until Podman is started]");
                }
                
                String os = System.getProperty("os.name").toLowerCase();
                System.err.println();
                System.err.println("  PRO-TIP: To fix Podman proper for " + (os.contains("win") ? "Windows" : "your OS") + ":");
                if (os.contains("win")) {
                    System.err.println("    1. Install Podman Desktop (or 'winget install RedHat.Podman')");
                    System.err.println("    2. run: podman machine init");
                    System.err.println("    3. run: podman machine start");
                } else if (os.contains("mac")) {
                    System.err.println("    1. brew install podman");
                    System.err.println("    2. podman machine init");
                    System.err.println("    3. podman machine start");
                } else {
                    System.err.println("    - Install podman via your package manager (apt/dnf/pacman)");
                }
                System.err.println();
            } else if (podmanReachable) {
                String image = System.getProperty("ARCCLAW_SANDBOX_IMAGE", 
                        System.getenv().getOrDefault("ARCCLAW_SANDBOX_IMAGE", "localhost/arcclaw-tool-runner:latest"));
                if (!canRun("podman", "image", "inspect", image, "--format", "{{.Id}}")) {
                    System.err.println("[ArcClaw] ⚠️  Podman image '" + image + "' missing. Containers will fail at runtime.");
                }
            }
        }
    }

    /**
     * Standalone Playwright setup — runs from bootstrap() directly,
     * outside interactiveSetupIfNeeded(), so it is never blocked by
     * the console==null or missing.isEmpty() early returns.
     */
    private static void promptPlaywrightSetupIfNeeded(Path binaryDir) {
        if (System.getenv("CI") != null || System.getenv("GITHUB_ACTIONS") != null) return;

        Path envFile = binaryDir.resolve(".env");
        Path browsersPath = binaryDir.resolve(".playwright-browsers");
        String playwrightProp = System.getProperty("ARCCLAW_TOOLS_PLAYWRIGHT_ENABLED",
                System.getenv("ARCCLAW_TOOLS_PLAYWRIGHT_ENABLED"));
        boolean playwrightEnabled = "true".equalsIgnoreCase(playwrightProp);

        boolean needsPrompt = (playwrightProp == null || playwrightProp.isBlank())
                || (playwrightEnabled && !PlaywrightBrowserInstaller.isChromiumInstalled(browsersPath));
        
        if (!needsPrompt) return;

        System.err.println();
        System.err.println("  ┌─ Playwright Browser Integration");
        System.err.println("  │  Enable real headless browser (Chromium) for complex web crawling/scraping?");
        System.err.println("  │  Required for JavaScript-heavy sites that simple fetchers cannot read.");
        System.err.println("  │");

        String response = readLineWithFallback(System.console(), playwrightEnabled
                ? "  └─ Download and install Chromium now? [Y/n]: "
                : "  └─ Enable Playwright? [y/N]: ");

        if (response == null || response.trim().isEmpty()) {
            if (playwrightEnabled && !PlaywrightBrowserInstaller.isChromiumInstalled(browsersPath)) {
                System.err.println("  │  (Non-interactive: auto-installing Chromium — already enabled in .env)");
                System.err.println("  │");
                PlaywrightBrowserInstaller.installChromium(browsersPath);
            } else {
                System.err.println();
                System.err.println("  ⚠  Non-interactive stdin detected (running via mise/task runner?).");
                System.err.println("     To enable Playwright, set in your .env:");
                System.err.println("       ARCCLAW_TOOLS_PLAYWRIGHT_ENABLED=true");
                System.err.println("     Then re-run — Chromium will auto-install on next start.");
            }
            return;
        }

        String tr = response.trim().toLowerCase();

        if (playwrightEnabled) {
            if (tr.isEmpty() || tr.startsWith("y")) {
                PlaywrightBrowserInstaller.installChromium(browsersPath);
            }
        } else if (tr.startsWith("y")) {
            patchEnvFile(envFile, "ARCCLAW_TOOLS_PLAYWRIGHT_ENABLED", "true");
            System.setProperty("ARCCLAW_TOOLS_PLAYWRIGHT_ENABLED", "true");
            initEnvFile(envFile, "PLAYWRIGHT_BROWSERS_PATH", browsersPath.toAbsolutePath().toString());
            initEnvFile(envFile, "PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD", "1");
            if (!PlaywrightBrowserInstaller.isChromiumInstalled(browsersPath)) {
                System.err.println("  │");
                System.err.println("  │  Chromium browser binary is not installed.");
                String ins = readLineWithFallback(System.console(), "  └─ Download and install Chromium now? [Y/n]: ");
                if (ins == null || ins.trim().isEmpty() || ins.trim().toLowerCase().startsWith("y")) {
                    PlaywrightBrowserInstaller.installChromium(browsersPath);
                }
            }
        } else if (tr.startsWith("n")) {
            patchEnvFile(envFile, "ARCCLAW_TOOLS_PLAYWRIGHT_ENABLED", "false");
            System.setProperty("ARCCLAW_TOOLS_PLAYWRIGHT_ENABLED", "false");
        }
        System.err.println();
    }

    private static void normalizePlaywrightPath(Path binaryDir) {
        String path = System.getProperty("PLAYWRIGHT_BROWSERS_PATH");
        if (path != null && !path.isBlank()) {
            Path p = Path.of(path);
            if (!p.isAbsolute()) {
                Path absolute = binaryDir.resolve(p).toAbsolutePath().normalize();
                System.setProperty("PLAYWRIGHT_BROWSERS_PATH", absolute.toString());
            }
        }
    }

    private static String readLineWithFallback(Console console, String prompt) {
        if (console != null) {
            return console.readLine(prompt); // null = EOF, callers handle it
        }
        System.err.print(prompt);
        System.err.flush();
        try {
            if (System.getenv("CI") == null && System.getenv("GITHUB_ACTIONS") == null) {
                BufferedReader reader = new BufferedReader(new InputStreamReader(System.in));
                String line = reader.readLine();
                return (line != null) ? line.trim() : null;
            } else {
                System.err.println(" (Non-interactive/CI detected)");
                return null;
            }
        } catch (Exception e) {
            return null;
        }
    }

    private static String readPasswordWithFallback(Console console, String prompt) {
        if (console != null) {
            char[] pw = console.readPassword(prompt);
            return (pw != null) ? new String(pw).trim() : "";
        }
        // Fallback for non-TTY environments (like mise run)
        return readLineWithFallback(null, prompt);
    }

    private static void drainInputBuffer() {
        if (System.console() != null) return; // Console doesn't need draining usually
        try {
            while (System.in.available() > 0) {
                System.in.read();
            }
        } catch (Exception ignored) {}
    }

    private static boolean canRun(String... cmd) {
        try {
            Process p = new ProcessBuilder(cmd).start();
            return p.waitFor(2, TimeUnit.SECONDS);
        } catch (Exception e) {
            return false;
        }
    }
