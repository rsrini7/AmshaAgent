package com.arcclaw.app.config;

import java.io.BufferedReader;
import java.io.Console;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import com.arcclaw.app.util.CliUtils;

/**
 * Bootstraps the application by resolving the binary directory, loading .env files,
 * extracting default config, and setting up environment variables before Quarkus starts.
 */
public class BinaryBootstrap {

    private static final Pattern ENV_PATTERN = Pattern.compile("^\\s*([A-Za-z_][A-Za-z0-9_.]*?)\\s*=\\s*(.*?)\\s*$");

    // Keys whose input should be hidden
    private static final Set<String> SENSITIVE_KEYS = Set.of(
        "ARCCLAW_LLM_API_KEY", "ARCCLAW_EMBED_API_KEY", "ARCCLAW_VAULT_PEPPER",
        "ARCCLAW_AUDIT_HMAC_KEY", "ARCCLAW_API_KEYS_INTERNAL", "ARCCLAW_API_KEYS_CI",
        "TELEGRAM_BOT_TOKEN",
        "ARCCLAW_BRAVE_API_KEY", "ARCCLAW_SERPER_API_KEY", "GITHUB_TOKEN"
    );

    // Keys that can be automatically generated by the bootstrap
    private static final Set<String> AUTO_GENERATABLE_KEYS = Set.of(
        "ARCCLAW_VAULT_PEPPER", "ARCCLAW_AUDIT_HMAC_KEY", 
        "ARCCLAW_API_KEYS_INTERNAL", "ARCCLAW_API_KEYS_CI", "ARCCLAW_API_KEYS_ADMIN"
    );

    public static void bootstrap(String[] args) {
        Path binaryDir = resolveBinaryDir();
        
        reexecWithLdPreloadIfNeeded(args);
        loadDotEnv(binaryDir);
        interactiveSetupIfNeeded(binaryDir, args);
        
        // 1. Resolve and Provision Data Directory
        String rawDataDir = System.getProperty("ARCCLAW_DATA_DIR", 
                System.getenv().getOrDefault("ARCCLAW_DATA_DIR", binaryDir.resolve("data").toString()));
        try {
            Path dirPath = Path.of(rawDataDir).toAbsolutePath().normalize();
            if (!Files.exists(dirPath)) {
                Files.createDirectories(dirPath);
                Files.createDirectories(dirPath.resolve("workspaces"));
            }
            System.setProperty("ARCCLAW_DATA_DIR", dirPath.toString());
        } catch (IOException e) {
            System.err.println("[ArcClaw] ⚠️  Warning: Failed to create data directory: " + e.getMessage());
        }

        // 2. Resolve and Provision Native Libraries (sqlite-vec)
        String vecPath = System.getProperty("ARCCLAW_RAG_VEC_PATH",
                System.getenv().getOrDefault("ARCCLAW_RAG_VEC_PATH", binaryDir.resolve("lib/vec0").toString()));
        try {
            Path absVecPath = Path.of(vecPath).toAbsolutePath().normalize();
            if (vecPath.contains("vec0")) { // Base path for extraction
                Vec0NativeLibraryInstaller.performInstallation(absVecPath.toString());
            }
            System.setProperty("ARCCLAW_RAG_VEC_PATH", absVecPath.toString());
        } catch (Exception e) {
            System.err.println("[ArcClaw] ⚠️  Warning: Failed to provision sqlite-vec: " + e.getMessage());
        }
    }

    private static Path resolveBinaryDir() {
        // 1. Native Image (GraalVM) — resolve to binary's actual location
        if (System.getProperty("org.graalvm.nativeimage.imagecode") != null) {
            String command = ProcessHandle.current().info().command().orElse("");
            if (!command.isEmpty()) {
                try {
                    Path p = Path.of(command).toAbsolutePath().getParent();
                    if (Files.exists(p)) return p;
                } catch (Exception ignored) {}
            }
            // /proc/self/exe fallback for Linux native
            try {
                Path proc = Path.of("/proc/self/exe");
                if (Files.exists(proc)) return proc.toRealPath().getParent();
            } catch (Exception ignored) {}
        }

        // 2. JAR / dev / IDE mode — always use CWD (where the user runs from)
        return Path.of(System.getProperty("user.dir")).toAbsolutePath();
    }

    private static void reexecWithLdPreloadIfNeeded(String[] args) {
        String os = System.getProperty("os.name").toLowerCase();
        if (!os.contains("linux")) return;
        if (System.getenv("ARCCLAW_LD_PRELOAD_SET") != null) return;
        if (System.getenv("LD_PRELOAD") != null) return; // Skip re-exec if already set by caller

        String libmPath = null;
        String[] candidates = {
            "/lib/x86_64-linux-gnu/libm.so.6",
            "/lib64/libm.so.6",
            "/usr/lib/x86_64-linux-gnu/libm.so.6",
            "/lib/aarch64-linux-gnu/libm.so.6"
        };

        for (String c : candidates) {
            if (Files.exists(Path.of(c))) {
                libmPath = c;
                break;
            }
        }

        if (libmPath == null) {
            System.err.println("[ArcClaw] ⚠️  Warning: libm.so.6 not found for LD_PRELOAD. Execution might fail on some Linux distros.");
            return;
        }

        String command = ProcessHandle.current().info().command().orElse("");
        if (command.isEmpty()) return;

        try {
            ProcessBuilder pb = new ProcessBuilder();
            pb.command().add(command);
            for (String arg : args) pb.command().add(arg);
            
            pb.environment().put("LD_PRELOAD", libmPath);
            pb.environment().put("ARCCLAW_LD_PRELOAD_SET", "1");
            pb.inheritIO();
            
            Process p = pb.start();
            System.exit(p.waitFor());
        } catch (Exception e) {
            System.err.println("[ArcClaw] ⚠️  Warning: Failed to re-exec with LD_PRELOAD: " + e.getMessage());
        }
    }

    static void loadDotEnv(Path dir) {
        // In native mode: this is the only .env loader — Quarkus config system
        //   hasn't started yet and DotenvConfigSourceProvider won't fire.
        // In JAR/dev mode: this front-runs Quarkus so CliUtils.validateRequiredEnvVars()
        //   can see the values before CDI starts. DotenvConfigSourceProvider will
        //   also load them — no conflict since we check env/sysprop before setting.
        Path envFile = dir.resolve(".env");
        if (!Files.exists(envFile)) return;

        try (BufferedReader reader = Files.newBufferedReader(envFile)) {
            String line;
            while ((line = reader.readLine()) != null) {
                line = line.trim();
                if (line.isEmpty() || line.startsWith("#")) continue;

                Matcher m = ENV_PATTERN.matcher(line);
                if (m.find()) {
                    String key = m.group(1);
                    String value = m.group(2).trim();

                    // Strip inline comments
                    if (value.contains(" #") || value.contains("\t#")) {
                        if (!(value.startsWith("\"") || value.startsWith("'"))) {
                            int idx = value.indexOf(" #");
                            if (idx == -1) idx = value.indexOf("\t#");
                            value = value.substring(0, idx).trim();
                        }
                    }

                    if (System.getenv(key) == null && System.getProperty(key) == null) {
                        System.setProperty(key, value);
                    }
                }
            }
        } catch (IOException e) {
            System.err.println("[ArcClaw] ⚠️  Warning: Failed to read .env: " + e.getMessage());
        }
    }

    private static void interactiveSetupIfNeeded(Path binaryDir, String[] args) {
        Console console = System.console();
        // Non-interactive (CI / piped): extract example and exit early
        if (console == null) {
            extractEnvExampleIfNeeded(binaryDir);
            return;
        }

        // 1. Initial State: LLM Provider selection determines what VarSpecs we need.
        // We prompt this BEFORE getMissingVarSpecs so the key hints (Groq/OpenRouter/etc) are correct.
        if (System.getProperty("ARCCLAW_LLM_PROVIDER") == null && System.getenv("ARCCLAW_LLM_PROVIDER") == null) {
            System.err.println();
            System.err.println("  ┌─ LLM Provider Select");
            System.err.println("  │  1. Groq (default) - ultra fast, free tier available");
            System.err.println("  │  2. OpenRouter - access any model (Llama 3, Claude, etc.)");
            System.err.println("  │  3. OpenAI - direct connection");
            System.err.println("  │  4. Ollama - local only (no API key required)");
            System.err.println("  │");
            String choice = console.readLine("  └─ Select provider [1-4, Default: 1]: ");
            String provider = switch (choice != null ? choice.trim() : "") {
                case "2" -> "openrouter";
                case "3" -> "openai";
                case "4" -> "ollama";
                default  -> "groq";
            };
            System.setProperty("ARCCLAW_LLM_PROVIDER", provider);
            // Will be persisted to .env during the loop below
        }

        List<CliUtils.VarSpec> missing = CliUtils.getMissingVarSpecs(args);
        if (missing.isEmpty()) return;

        Path envFile = binaryDir.resolve(".env");

        // Seed .env from example if missing so we have a place to patch
        if (!Files.exists(envFile)) {
            try (InputStream in = BinaryBootstrap.class.getResourceAsStream("/env-example")) {
                if (in != null) Files.copy(in, envFile, StandardCopyOption.REPLACE_EXISTING);
            } catch (IOException ignored) {}
        }

        // Always ensure ARCCLAW_LLM_PROVIDER and auto-seed are in .env
        patchEnvFile(envFile, "ARCCLAW_LLM_PROVIDER", System.getProperty("ARCCLAW_LLM_PROVIDER", "groq"));
        patchEnvFile(envFile, "ARCCLAW_AUTO_SEED_SECRETS", "true");
        patchEnvFile(envFile, "ARCCLAW_SANDBOX_NETWORK", "host");

        // Use tmpdir specifically on macOS to avoid /run/arcclaw read-only warnings
        String defaultTransport = System.getProperty("os.name", "").toLowerCase().contains("mac") ? "tmpdir" : "tmpfs";
        patchEnvFile(envFile, "ARCCLAW_SANDBOX_SECRET_TRANSPORT", defaultTransport);

        System.err.println();
        System.err.println("╔══════════════════════════════════════════════════════════╗");
        System.err.println("║         ArcClaw — First-Run Interactive Setup            ║");
        System.err.println("╚══════════════════════════════════════════════════════════╝");
        System.err.println();
        System.err.println("  " + missing.size() + " required value(s) need configuration.");
        System.err.println("  Saved to: " + envFile);
        System.err.println("  Press Enter to skip a value (you can fill it in .env later).");
        System.err.println();

        boolean skipTelegram = false;
        boolean askedTelegram = false;
        for (CliUtils.VarSpec spec : missing) {
            // Optional: Ask for Telegram enablement once
            if (spec.key.startsWith("TELEGRAM_") || spec.key.startsWith("ARCCLAW_TELEGRAM_")) {
                if (!askedTelegram) {
                    System.err.println("  ┌─ Telegram Integration");
                    System.err.println("  │  Would you like to enable the Telegram bot interface?");
                    System.err.println("  │");
                    String response = console.readLine("  └─ Enable Telegram? [y/N]: ");
                    askedTelegram = true;
                    if (response == null || !response.trim().toLowerCase().startsWith("y")) {
                        skipTelegram = true;
                        patchEnvFile(envFile, "ARCCLAW_TELEGRAM_ENABLED", "false");
                        System.setProperty("ARCCLAW_TELEGRAM_ENABLED", "false");
                    } else {
                        patchEnvFile(envFile, "ARCCLAW_TELEGRAM_ENABLED", "true");
                        System.setProperty("ARCCLAW_TELEGRAM_ENABLED", "true");
                        System.err.println();
                    }
                }
                if (skipTelegram) continue;
            }

            // Optional: Ask for GitHub token
            if (spec.key.equals("GITHUB_TOKEN")) {
                System.err.println("  ┌─ GitHub repository access");
                System.err.println("  │  Would you like to provide a GitHub token for the Coder/Researcher tools?");
                System.err.println("  │  (Search and edit repositories directly from ArcClaw)");
                System.err.println("  │");
                String response = console.readLine("  └─ Configure GitHub? [y/N]: ");
                if (response == null || !response.trim().toLowerCase().startsWith("y")) {
                    System.err.println("     [skipped]");
                    System.err.println();
                    continue;
                }
                System.err.println();
            }

            if (spec.key.equals("ARCCLAW_SERPER_API_KEY")) {
                System.err.println("  ┌─ Serper Search Integration");
                System.err.println("  │  Enable Google Search for Researcher agent via Serper.dev?");
                System.err.println("  │");
                String response = console.readLine("  └─ Configure Serper? [y/N]: ");
                if (response == null || !response.trim().toLowerCase().startsWith("y")) {
                    System.err.println("     [skipped]");
                    System.err.println();
                    continue;
                }
                System.err.println();
            }

            if (spec.key.equals("ARCCLAW_BRAVE_API_KEY")) {
                System.err.println("  ┌─ Brave Search Integration");
                System.err.println("  │  Enable Brave Search for Researcher agent?");
                System.err.println("  │");
                String response = console.readLine("  └─ Configure Brave? [y/N]: ");
                if (response == null || !response.trim().toLowerCase().startsWith("y")) {
                    System.err.println("     [skipped]");
                    System.err.println();
                    continue;
                }
                System.err.println();
            }

            boolean sensitive = SENSITIVE_KEYS.contains(spec.key);
            System.err.println("  ┌─ " + spec.key);
            System.err.println("  │  " + spec.description);
            for (String hint : spec.howToGet) {
                System.err.println("  │  " + hint);
            }
            if (spec.key.equals("ARCCLAW_VAULT_PEPPER")) {
                System.err.println("  │  ⚠️  WARNING: Changing this will make existing encrypted data undecryptable.");
            }
            System.err.println("  │");

            String value;
            if (sensitive) {
                String promptText = "  └─ Enter value" + (AUTO_GENERATABLE_KEYS.contains(spec.key) ? " (Enter to auto-generate, input hidden): " : " (input hidden): ");
                char[] pw = console.readPassword(promptText);
                value = (pw != null) ? new String(pw).trim() : "";
                if (value.isEmpty() && AUTO_GENERATABLE_KEYS.contains(spec.key)) {
                    value = generateRandomValue();
                }
            } else {
                String promptText = "  └─ Enter value" + (AUTO_GENERATABLE_KEYS.contains(spec.key) ? " (Enter to auto-generate): " : ": ");
                String line = console.readLine(promptText);
                value = (line != null) ? line.trim() : "";
                if (value.isEmpty() && AUTO_GENERATABLE_KEYS.contains(spec.key)) {
                    value = generateRandomValue();
                }
            }

            if (value.isBlank()) {
                System.err.println("     [skipped — add manually to: " + envFile + "]");
            } else {
                patchEnvFile(envFile, spec.key, value);
                System.setProperty(spec.key, value);

                // For Quarkus Config Maps (like arcclaw.api.keys), we also set the dot-notation property
                // if the key follows the standard ARCCLAW_ prefix pattern.
                if (spec.key.startsWith("ARCCLAW_")) {
                    String dotPath = spec.key.toLowerCase().replace("_", ".");
                    System.setProperty(dotPath, value);
                }
                
                System.err.println("     ✓ Saved");
            }
            System.err.println();
        }

        System.err.println("[ArcClaw] ✓ Setup complete. Configuration saved to: " + envFile);
        System.err.println();
    }

    /**
     * Replaces the value of an existing KEY=... line in-place, or appends
     * KEY=value at the end if the key is not found.
     */
    private static void patchEnvFile(Path envFile, String key, String value) {
        try {
            if (!Files.exists(envFile)) {
                Files.writeString(envFile, key + "=" + value + System.lineSeparator());
                return;
            }
            String content = Files.readString(envFile);
            // Replace KEY=<anything> line (including blank values and placeholders)
            String patched = content.replaceAll(
                "(?m)^" + Pattern.quote(key) + "=.*$",
                Matcher.quoteReplacement(key + "=" + value)
            );
            if (!patched.equals(content)) {
                Files.writeString(envFile, patched);
            } else {
                // Key not present in file at all — append it
                Files.writeString(envFile,
                    System.lineSeparator() + key + "=" + value + System.lineSeparator(),
                    StandardOpenOption.APPEND);
            }
        } catch (IOException e) {
            System.err.println("[ArcClaw] ⚠️  Could not update .env: " + e.getMessage());
        }
    }

    private static void extractEnvExampleIfNeeded(Path dir) {
        Path envFile = dir.resolve(".env");
        if (Files.exists(envFile)) return;

        Path exampleFile = dir.resolve(".env.example");
        if (!Files.exists(exampleFile)) {
            try (InputStream in = BinaryBootstrap.class.getResourceAsStream("/env-example")) {
                if (in == null) {
                    System.err.println("[ArcClaw] ⚠️  Warning: env-example not found in classpath.");
                    return;
                }
                Files.copy(in, exampleFile, StandardCopyOption.REPLACE_EXISTING);
                System.err.println("[ArcClaw] No .env found. Created .env.example next to the binary.");
                System.err.println("[ArcClaw] Copy and configure it:  cp .env.example .env");
            } catch (IOException e) {
                System.err.println("[ArcClaw] ⚠️  Warning: Failed to extract .env.example: " + e.getMessage());
            }
        } else {
            System.err.println("[ArcClaw] No .env found. Use the existing .env.example:  cp .env.example .env");
        }
    }
 
    private static String generateRandomValue() {
        byte[] bytes = new byte[32];
        new SecureRandom().nextBytes(bytes);
        return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
    }
}
