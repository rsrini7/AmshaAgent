    private static void initEnvFile(Path envFile, String key, String value) {
        patchEnvFile(envFile, key, value, PatchMode.INIT);
    }

    private static void patchEnvFile(Path envFile, String key, String value) {
        patchEnvFile(envFile, key, value, PatchMode.UPDATE);
    }

    private static void forcePatchEnvFile(Path envFile, String key, String value) {
        patchEnvFile(envFile, key, value, PatchMode.FORCE);
    }

    private enum PatchMode { INIT, UPDATE, FORCE }

    private static void patchEnvFile(Path envFile, String key, String value, PatchMode mode) {
        try {
            if (!Files.exists(envFile)) {
                Files.writeString(envFile, key + "=" + value + System.lineSeparator());
                return;
            }
            String content = Files.readString(envFile);
            
            Pattern pattern = Pattern.compile("(?m)^" + Pattern.quote(key) + "=.*$");
            Matcher matcher = pattern.matcher(content);
            
            if (matcher.find()) {
                String currentLine = matcher.group();
                String newLine = key + "=" + value;
                
                boolean needsPatch = switch (mode) {
                    case FORCE  -> true;
                    case UPDATE -> !currentLine.equals(newLine);
                    case INIT   -> {
                        String currentValue = currentLine.substring(key.length() + 1).trim();
                        yield currentValue.isEmpty() || currentValue.contains("xxxx") || 
                              currentValue.contains("<") || currentValue.contains("changeme") ||
                              currentValue.contains("_your_") || currentValue.contains("ABCdef");
                    }
                };

                if (needsPatch) {
                    int count = 0;
                    matcher.reset();
                    while (matcher.find()) count++;
                    if (count > 1) {
                        System.err.println("[ArcClaw] ⚠️  Warning: Duplicate key '" + key + "' found in .env. Cleaning up...");
                        content = pattern.matcher(content).replaceAll(Matcher.quoteReplacement(newLine));
                    } else {
                        content = pattern.matcher(content).replaceFirst(Matcher.quoteReplacement(newLine));
                    }
                    Files.writeString(envFile, content);
                }
            } else {
                String separator = content.endsWith(System.lineSeparator()) ? "" : System.lineSeparator();
                Files.writeString(envFile,
                    separator + key + "=" + value + System.lineSeparator(),
                    StandardOpenOption.APPEND);
            }
        } catch (IOException e) {
            System.err.println("[ArcClaw] ⚠️  Could not update .env: " + e.getMessage());
        }
    }

    private static void extractEnvExampleIfNeeded(Path dir) {
        Path envFile = dir.resolve(".env");
        if (Files.exists(envFile)) return;

        Path exampleFile = dir.resolve(".env.example");
        if (!Files.exists(exampleFile)) {
            try (InputStream in = BinaryBootstrap.class.getResourceAsStream("/env-example")) {
                if (in == null) {
                    System.err.println("[ArcClaw] ⚠️  Warning: env-example not found in classpath.");
                    return;
                }
                Files.copy(in, exampleFile, StandardCopyOption.REPLACE_EXISTING);
                System.err.println("[ArcClaw] No .env found. Created .env.example next to the binary.");
                System.err.println("[ArcClaw] Copy and configure it:  cp .env.example .env");
            } catch (IOException e) {
                System.err.println("[ArcClaw] ⚠️  Warning: Failed to extract .env.example: " + e.getMessage());
            }
        }
    }
 
    private static String generateRandomValue() {
        byte[] bytes = new byte[32];
        new SecureRandom().nextBytes(bytes);
        return Base64.getEncoder().encodeToString(bytes);
    }

    private static void validateAndAutoFixSecurityKeys(Path binaryDir) {
        Path envFile = binaryDir.resolve(".env");
        boolean anyFixed = false;
        for (String key : BASE64_KEYS) {
            String value = System.getProperty(key, System.getenv(key));
            if (value == null || value.isBlank()) continue;
            boolean valid = false;
            try {
                byte[] decoded = Base64.getDecoder().decode(value);
                valid = decoded.length >= 16;
            } catch (IllegalArgumentException ignored) {}
            if (!valid) {
                try {
                    String generated = Base64.getEncoder().encodeToString(
                        SecureRandom.getInstanceStrong().generateSeed(32));
                    System.err.println("[ArcClaw] ⚠️  " + key + " invalid Base64 — regenerating.");
                    patchEnvFile(envFile, key, generated);
                    System.setProperty(key, generated);
                    anyFixed = true;
                } catch (Exception e) {
                    System.err.println("[ArcClaw] ❌ Failed to generate security key for " + key + ": " + e.getMessage());
                }
            }
        }
        if (anyFixed) loadDotEnv(binaryDir);
    }

