package com.amsha.app.connector.github;

import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Pattern;

/** Canonical path and first-source policy for GitHub documentation connections. */
final class GitHubReadmeSourcePolicy {
    static final String FIRST_REPOSITORY = "rsrini7/AmshaAgent";
    static final List<String> FIRST_ALLOWED_PATHS = List.of("README.md", "docs/**/*.md");

    private static final Pattern REPOSITORY_PATTERN =
            Pattern.compile("[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})/[A-Za-z0-9_.-]{1,100}");
    private static final Set<String> GENERATED_SEGMENTS = Set.of(
            "generated",
            "_generated",
            "__generated__",
            "autogenerated",
            "build",
            "dist",
            "target",
            "site",
            "_site",
            "coverage",
            "node_modules",
            "vendor",
            "out");

    private GitHubReadmeSourcePolicy() {}

    static GitHubReadmeConnectionSettings firstConnection() {
        return new GitHubReadmeConnectionSettings(FIRST_REPOSITORY, FIRST_ALLOWED_PATHS);
    }

    static GitHubReadmeConnectionSettings validateFirstConnection(GitHubReadmeConnectionSettings settings) {
        if (settings == null
                || settings.repository() == null
                || !REPOSITORY_PATTERN.matcher(settings.repository()).matches()
                || !FIRST_REPOSITORY.equals(settings.repository())
                || settings.allowedPaths().size() != FIRST_ALLOWED_PATHS.size()
                || settings.allowedPaths().stream().anyMatch(path -> path == null || path.isBlank())
                || settings.allowedPaths().stream().distinct().count()
                        != settings.allowedPaths().size()) {
            throw new IllegalArgumentException(
                    "GitHub connection settings are outside the approved first-source scope");
        }
        if (!Set.copyOf(settings.allowedPaths()).equals(Set.copyOf(FIRST_ALLOWED_PATHS))) {
            throw new IllegalArgumentException(
                    "GitHub connection settings are outside the approved first-source scope");
        }
        return firstConnection();
    }

    static boolean isAllowedMarkdownPath(GitHubReadmeConnectionSettings settings, String path) {
        validateFirstConnection(settings);
        if (!isSafeRelativePath(path) || isHiddenPath(path) || isGeneratedPath(path)) {
            return false;
        }
        if ("README.md".equals(path)) {
            return true;
        }
        if (!path.startsWith("docs/")) {
            return false;
        }
        String lowerPath = path.toLowerCase(Locale.ROOT);
        return lowerPath.endsWith(".md");
    }

    static boolean isSafeRelativePath(String path) {
        if (path == null || path.isBlank() || path.length() > 1024 || path.startsWith("/") || path.contains("\\")) {
            return false;
        }
        for (int index = 0; index < path.length(); index++) {
            if (Character.isISOControl(path.charAt(index))) {
                return false;
            }
        }
        String[] segments = path.split("/", -1);
        for (String segment : segments) {
            if (segment.isBlank() || ".".equals(segment) || "..".equals(segment)) {
                return false;
            }
        }
        return true;
    }

    static boolean isGeneratedPath(String path) {
        String lowerPath = path.toLowerCase(Locale.ROOT);
        for (String segment : lowerPath.split("/")) {
            if (GENERATED_SEGMENTS.contains(segment)) {
                return true;
            }
        }
        String fileName = lowerPath.substring(lowerPath.lastIndexOf('/') + 1);
        return fileName.contains("generated");
    }

    private static boolean isHiddenPath(String path) {
        for (String segment : path.split("/")) {
            if (segment.startsWith(".")) {
                return true;
            }
        }
        return false;
    }
}
