package com.amsha.rag;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Inject;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import com.amsha.persistence.api.VectorIndexCompatibility;
import com.amsha.persistence.api.VectorIndexMetadataPort;
import com.amsha.persistence.api.VectorIndexNamespace;

import org.jboss.logging.Logger;

import io.micrometer.core.instrument.MeterRegistry;

/**
 * Service that coordinates candidate chunk reranking via {@link RerankerPort}
 * with deterministic fallback to the synthetic RRF fusion ordering.
 *
 * <p>Normative Fallback Contract (Issue 04):
 * <ul>
 *   <li>When no reranker is configured or active, candidates are returned in original RRF order
 *       and tagged metric {@code amsha.rag.rerank.fallback(reason=no_provider)} is incremented.</li>
 *   <li>When reranking fails due to an exception, candidates are returned in original RRF order,
 *       a safe reason-only warning is logged, and {@code amsha.rag.rerank.fallback(reason=execution_error)} is incremented.</li>
 *   <li>When an embedding descriptor mismatch occurs, candidates are returned in original RRF order
 *       and {@code amsha.rag.rerank.fallback(reason=descriptor_mismatch)} is incremented.</li>
 *   <li>When reranker output is corrupt, incomplete, or contains hallucinated/duplicate chunks, candidates
 *       are returned in original RRF order and an appropriate fallback metric is incremented.</li>
 *   <li>Candidate scores {@link ScoredChunk#score()} are strictly preserved byte-for-byte in all cases.</li>
 * </ul>
 */
@ApplicationScoped
public class RerankingService {

    private static final Logger log = Logger.getLogger(RerankingService.class);
    static final String FALLBACK_METRIC_NAME = "amsha.rag.rerank.fallback";

    @Inject
    Instance<RerankerPort> rerankerInstance;

    @Inject
    Instance<MeterRegistry> meterRegistryInstance;

    @Inject
    Instance<VectorIndexMetadataPort> vectorMetadataPortInstance;

    /**
     * Reranks the given candidate chunks against the query.
     *
     * @param query      the search query
     * @param candidates the candidate chunks generated by FTS5/BM25 and vector search
     * @return the reranked chunks, or original candidates in RRF order on fallback
     */
    public List<RerankedChunk> rerank(String query, List<ScoredChunk> candidates) {
        if (candidates == null || candidates.isEmpty()) {
            return List.of();
        }

        String descriptorFallbackReason = descriptorFallbackReason();
        if (descriptorFallbackReason != null) {
            recordFallback(descriptorFallbackReason);
            return toFallbackRerankedList(candidates);
        }

        if (rerankerInstance == null || rerankerInstance.isUnsatisfied()) {
            recordFallback("no_provider");
            return toFallbackRerankedList(candidates);
        }

        try {
            RerankerPort port = rerankerInstance.get();
            List<RerankedChunk> reranked = port.rerank(query, candidates);
            return validateAndReconstitute(candidates, reranked);
        } catch (Exception e) {
            log.warnf(
                    "RAG reranker execution failed (%s); falling back to hybrid RRF ordering",
                    e.getClass().getSimpleName());
            recordFallback("execution_error");
            return toFallbackRerankedList(candidates);
        }
    }

    /**
     * Records fallback when an embedding descriptor mismatch is detected by the caller.
     */
    public void recordDescriptorMismatchFallback() {
        recordFallback("descriptor_mismatch");
    }

    private String descriptorFallbackReason() {
        if (vectorMetadataPortInstance == null || vectorMetadataPortInstance.isUnsatisfied()) {
            return "metadata_unavailable";
        }
        try {
            VectorIndexMetadataPort port = vectorMetadataPortInstance.get();
            Map<VectorIndexNamespace, VectorIndexCompatibility> snapshot = port.compatibilitySnapshot();
            if (snapshot == null || snapshot.isEmpty()) {
                return "metadata_unavailable";
            }
            for (VectorIndexCompatibility comp : snapshot.values()) {
                if (comp == null || comp.status() == VectorIndexCompatibility.Status.UNAVAILABLE) {
                    return "metadata_unavailable";
                }
                if (comp.status() == VectorIndexCompatibility.Status.MISMATCH
                        || comp.status() == VectorIndexCompatibility.Status.MISSING_METADATA) {
                    return "descriptor_mismatch";
                }
            }
            return null;
        } catch (Exception _) {
            return "metadata_unavailable";
        }
    }

    private List<RerankedChunk> validateAndReconstitute(List<ScoredChunk> candidates, List<RerankedChunk> reranked) {
        if (reranked == null || reranked.isEmpty()) {
            recordFallback("empty_result");
            return toFallbackRerankedList(candidates);
        }

        if (reranked.size() != candidates.size()) {
            recordFallback("cardinality_mismatch");
            return toFallbackRerankedList(candidates);
        }

        Map<String, ScoredChunk> candidateMap = new HashMap<>(candidates.size());
        for (ScoredChunk c : candidates) {
            candidateMap.put(c.chunkId(), c);
        }

        Set<String> seenIds = new HashSet<>(candidates.size());
        List<RerankedChunk> validated = new ArrayList<>(candidates.size());
        double previousRerankScore = Double.POSITIVE_INFINITY;

        for (RerankedChunk r : reranked) {
            if (r == null || r.chunk() == null) {
                recordFallback("invalid_result");
                return toFallbackRerankedList(candidates);
            }
            String chunkId = r.chunkId();
            if (chunkId == null || !candidateMap.containsKey(chunkId) || !seenIds.add(chunkId)) {
                recordFallback("identity_mismatch");
                return toFallbackRerankedList(candidates);
            }
            double rerankScore = r.rerankScore();
            if (!Double.isFinite(rerankScore) || rerankScore > previousRerankScore) {
                recordFallback("order_invalid");
                return toFallbackRerankedList(candidates);
            }
            previousRerankScore = rerankScore;
            // Strict preservation: ensure the original ScoredChunk instance (and its synthetic RRF score) is retained
            ScoredChunk original = candidateMap.get(chunkId);
            validated.add(new RerankedChunk(original, rerankScore));
        }

        return validated;
    }

    private void recordFallback(String reason) {
        if (meterRegistryInstance != null && !meterRegistryInstance.isUnsatisfied()) {
            try {
                meterRegistryInstance
                        .get()
                        .counter(FALLBACK_METRIC_NAME, "reason", reason)
                        .increment();
            } catch (Exception e) {
                log.debugf(
                        "Failed to record rerank fallback metric (%s)",
                        e.getClass().getSimpleName());
            }
        }
    }

    private static List<RerankedChunk> toFallbackRerankedList(List<ScoredChunk> candidates) {
        return candidates.stream().map(c -> new RerankedChunk(c, c.score())).toList();
    }
}
